update public.modules m set title = v.title
from public.courses c, (values
  (1, 'Занятие 0. Вводное'),
  (2, 'Занятие 1. Колесо'),
  (3, 'Занятие 2. Физика и характеристики колеса'),
  (4, 'Занятие 3. Исследования и работа конструктора'),
  (5, 'Занятия 4–5. Автомобиль'),
  (6, 'Занятия 6–7. Свой проект')
) as v (sort, title)
where c.slug = 'wheel' and m.course_id = c.id and m.sort = v.sort;
