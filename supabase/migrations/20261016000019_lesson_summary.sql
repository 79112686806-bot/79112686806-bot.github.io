-- Краткое содержание модуля для страницы курса (видно всем, как и название).
-- Несколько строк — на странице выводятся списком.
alter table public.lessons add column if not exists summary text;

-- Курс «Колесо»: подзаголовок, описание и краткое содержание модулей
update public.courses set
  subtitle    = 'Первый технологический прорыв в истории человечества',
  description = 'Путь от изобретения колеса до современных автомобилей.'
where slug = 'wheel';

update public.lessons l set title = v.title, summary = v.summary
from public.modules m, public.courses c,
  (values
    (1, 1, 'Вводное занятие',
     E'Кто такие инженеры\nЧто значит «мыслить как инженер»\nИнженерия в прошлом, настоящем и будущем'),
    (2, 1, 'Модуль 1. История изобретения и функции колеса', null),
    (4, 2, 'Модуль 6. Что должен учитывать инженер-конструктор',
     'Функционал, надёжность, безопасность, удобство использования, дизайн изделия, экономичность производства, психология потребителя'),
    (5, 1, 'Модуль 7. Автомобиль',
     'Функционал, история создания и развития, конструкция автомобиля, принципы работы, маркетинговые вопросы, перспективы развития автомобилей')
  ) as v(mod_sort, lesson_sort, title, summary)
where c.slug = 'wheel' and m.course_id = c.id and m.sort = v.mod_sort
  and l.module_id = m.id and l.sort = v.lesson_sort;
