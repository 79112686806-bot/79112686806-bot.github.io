## Трение

Трение — это физическое явление, когда возникает сила сопротивления при соприкосновении двух тел, например когда охотники тащат по земле добычу. Эта сила «тормозит» движение.

Почему возникает трение? Есть две главные причины:
- Шероховатость поверхностей. Даже если поверхность кажется идеально гладкой, например как поверхность стола, под микроскопом на ней видны бугорки и впадины. Когда два тела соприкасаются, эти неровности цепляются друг за друга, мешая скольжению.
- Межмолекулярное притяжение. В местах, где поверхности прилегают особенно плотно, молекулы начинают притягиваться друг к другу. Чтобы сдвинуть тело, нужно сначала «оторвать» эти сцепленные участки.

## Скольжение

Возвращаемся к нашим охотникам. Если вдруг они охотились зимой, то могли использовать сани. Сила сопротивления при этом стала гораздо меньше, чем если просто тащить.

Скольжение — это когда одно тело перемещается (волочится или скользит) по поверхности другого. При этом возникает трение, которое называется трением скольжения. Например, санки или лыжи скользят по снегу.

## Качение

Качение — это вид движения твёрдого тела (чаще всего круглого: шара, цилиндра, колеса), при котором оно перекатывается по поверхности, а не скользит по ней.

Но мы идём дальше. Люди, даже древние, тем и отличаются от животных, что могут думать. И вот они придумали колесо. Да, когда колесо катится, тоже возникает трение — в точках соприкосновения колеса с поверхностью. Оно называется трением качения. Это не «истирание» поверхностей, как при трении скольжения, а в первую очередь потери энергии на деформацию и внутреннее трение, но нам сейчас такие тонкости не нужны. Мы скажем только, что это трение (сила сопротивления) во много раз меньше, чем когда мы тащим груз волоком или перемещаем на санках.

**Трение качения меньше, чем трение скольжения.**

На первом занятии мы разбирали пример с тачкой. Обратимся к цифрам. Сила трения качения обычно в 10–50 раз меньше, чем сила трения скольжения для тех же материалов и нагрузки. Поэтому для движения тачки нужно прикладывать гораздо меньше силы.

