## Размер и форма колёс

Дорогой друг, ты уже включился в работу, ты уже проработал 2 занятия, ты растёшь, ты думаешь как инженер, мы уважаем тебя и переходим к изложению информации «по-деловому», «по-взрослому».

Размер и ширина колёс — это не просто «как красивее смотрится», а параметры, которые напрямую меняют физику движения: от того, как быстро машина разгоняется, до того, насколько уверенно она держит дорогу в повороте.

**Размер (диаметр) колеса влияет на динамику разгона.** Колесо большего размера (диаметра) обычно тяжелее, и двигателю сложнее его раскрутить. Это снижает динамику (разгон становится более «вялым»).

**Размер (диаметр) колеса влияет на устойчивость.** Большие колёса поднимают клиренс и немного поднимают центр тяжести автомобиля. Это делает машину чуть более склонной к кренам в поворотах и менее стабильной на резких манёврах.

## Ширина колеса

**Ширина колеса влияет на скорость и расход топлива.** Широкие шины имеют большее пятно контакта с дорогой, чем узкие, и это немного увеличивает расход топлива и чуть снижает максимальную скорость и разгон.

**Ширина колеса влияет на устойчивость.** Более широкая шина даёт большее пятно контакта, поэтому лучше держит боковые нагрузки и позволяет проходить повороты на более высокой скорости без сноса. На сухом покрытии это повышает устойчивость в манёврах и сокращает тормозной путь.

У широкой шины больше площадь, которую нужно «очистить» от воды. Если водоотводящие канавки не справляются, то на мокрой дороге широкая резина может стать менее устойчивой, чем узкая.

> **Задание.** Посмотри, пожалуйста, протектор шин на маминой или папиной машине и разгляди водоотводящие канавки.

На снегу, грязи и песке узкая шина «прорезает» слой до твёрдой поверхности, а широкая «плывёт» сверху. Поэтому в таких условиях узкие колёса могут дать лучшую устойчивость и проходимость. Но у каждой медали есть и обратная сторона, и широкие шины как раз за счёт большего соприкосновения могут выигрывать в проходимости. Здесь большую роль скорее играет протектор. В общем, вот тебе информация к размышлению.

