-- Программа курса «Колесо»: блоки = занятия, внутри — модули (единица покупки).
-- Тексты модулей и таблицы исследований — в миграции 20261011000017_wheel_program_v2.sql
-- (на новой базе запустите её ещё раз после seed — она повторно безопасна).
insert into public.modules (course_id, sort, title)
select c.id, v.sort, v.title
from public.courses c
cross join (values
  (1, 'Занятие 1. Вводное'),
  (2, 'Занятие 2. Колесо'),
  (3, 'Занятие 3. Физика и характеристики колеса'),
  (4, 'Занятие 4. Исследования и работа конструктора'),
  (5, 'Занятия 5–6. Автомобиль'),
  (6, 'Занятия 7–8. Свой проект')
) as v (sort, title)
where c.slug = 'wheel'
on conflict (course_id, sort) do nothing;

insert into public.lessons (module_id, sort, title)
select m.id, v.lesson_sort, v.title
from (values
  (1, 1, 'Вводное занятие'),
  (2, 1, 'Модуль 1. История изобретения и функции колеса'),
  (3, 1, 'Модуль 2. Трение, скольжение, качение'),
  (3, 2, 'Модуль 3. Характеристики колеса: размер и ширина'),
  (3, 3, 'Модуль 4. Перспективные идеи развития колеса'),
  (4, 1, 'Модуль 5. Исследования и измерения'),
  (4, 2, 'Модуль 6. Что должен учитывать инженер-конструктор'),
  (5, 1, 'Модуль 7. Автомобиль'),
  (6, 1, 'Модуль 8. Разработка собственного проекта автомобиля')
) as v (module_sort, lesson_sort, title)
join public.modules m on m.sort = v.module_sort
join public.courses c on c.id = m.course_id and c.slug = 'wheel'
on conflict (module_id, sort) do nothing;

-- Пустая закрытая часть для каждой темы (видео и материалы добавим позже)
